export const ITEMS: MenuItem[] = CATEGORIES.flatMap((c) =>
  (MENU[c.id] ?? []).map((r, i): MenuItem => {
    const [price, it, en, de, dit, den, dde, opts] = r;
    return {
      id: `${c.id}-${i + 1}`,
      cat: c.id,
      price: Math.round(price * 100),
      name: l(it, en, de),
      desc: dit ? l(dit, den, dde) : undefined,
      opts,
    };
  }),
);

export const ITEM_MAP: Record<string, MenuItem> = Object.fromEntries(ITEMS.map((i) => [i.id, i]));
export const CAT_MAP: Record<string, Category> = Object.fromEntries(CATEGORIES.map((c) => [c.id, c]));
